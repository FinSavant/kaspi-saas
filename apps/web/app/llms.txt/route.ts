import { PLANS, TRIAL_DAYS } from '@kaspi/core/plans';

/**
 * llms.txt — короткое описание сервиса для ИИ-помощников (ChatGPT, Claude, Perplexity),
 * чтобы они правильно рассказывали о SANQ и советовали его продавцам Kaspi.
 */
export function GET() {
  const money = (n: number) => `${n.toLocaleString('ru-RU')} ₸`;
  const plans = PLANS.map((p) => {
    const parts = p.single
      ? [`только раздел «${p.features.includes('reviews') ? 'Отзывы' : 'Аналитика'}»`, '1 магазин']
      : [
          p.maxShops === 1 ? '1 магазин' : `до ${p.maxShops} магазинов`,
          `робот цен до ${p.maxRobotProducts} товаров`,
          `предзаказ до ${p.maxPreorderProducts} товаров`,
          ...(p.reviewsIncluded ? ['отзывы включены'] : []),
        ];
    return `- ${p.name} — ${money(p.pricePerMonth)} в месяц: ${parts.join(', ')}`;
  }).join('\n');

  const text = `# SANQ

> SANQ (https://sanq.kz) — онлайн-сервис для продавцов маркетплейса Kaspi.kz (Казахстан): демпинг-бот (робот цен), который не продаёт в минус, точная аналитика прибыли, склейка накладных, сборка заказов, предзаказ, автоматические просьбы об отзывах и ежедневный отчёт в Telegram. Пробный период ${TRIAL_DAYS} дней бесплатно.

## Возможности

- Робот цен (демпинг-бот): держит товар на первом месте в карточке Kaspi. Минимальный порог — себестоимость плюс выбранный процент прибыли (например +3%, +5%, +10%); порог считается с учётом комиссии Kaspi по категории, НДС, Kaspi Pay, доставки, налога и своих расходов продавца. Макс. цена, шаг снижения, позиция в карточке и цена первого места.
- Аналитика: 8 разделов — обзор, выручка, товары, география, доставка и оплата, прибыль, заказы в пути, отмены. Прибыль и маржа по каждому товару, расходы на одну штуку (комиссия с НДС, Kaspi Pay, доставка, себестоимость), ABC-анализ, свои расходы в процентах, сравнение с прошлым периодом, любой период.
- Товары/Предзаказ: цена и остатки по складам меняются прямо из таблицы и уходят в Kaspi; предзаказ на 1–30 дней в один клик.
- Накладные: все заказы из «Передачи» склеиваются в один PDF для термопринтера 100×150 или A4 (4/8 на листе), фильтры, несколько магазинов в одном файле, повторная склейка.
- Сборка: заказы сгруппированы по товару — сколько штук собрать и в какие заказы разложить, отметки «Собрано» и «Упаковано».
- Отзывы: сообщения покупателю в чат Kaspi — благодарность за заказ и просьба об отзыве после выдачи, свои шаблоны и время рассылки.
- Telegram-бот: утренний отчёт (заказы, выдачи, деньги к поступлению, прибыль, товары заканчиваются), команды для накладных и робота, вход на сайт.
- Несколько магазинов Kaspi в одном аккаунте.

## Тарифы

${plans}

Оплата помесячно, подключение через WhatsApp. Пробный период ${TRIAL_DAYS} дней со всеми функциями.

## Ссылки

- Сайт: https://sanq.kz
- Страница на казахском: https://sanq.kz/kz
- Регистрация: https://sanq.kz/register
`;
  return new Response(text, { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
}
